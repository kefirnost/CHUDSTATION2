using System.Globalization;
using Content.Shared.Traits;
using Robust.Client.AutoGenerated;
using Robust.Client.GameObjects;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client.Lobby.UI.Roles;

[GenerateTypedNameReferences]
public sealed partial class TraitPreferenceSelector : Control
{
    public int Cost;

    public bool Preference
    {
        get => Checkbox.Pressed;
        set => Checkbox.Pressed = value;
    }

    public event Action<bool>? PreferenceChanged;

    public TraitPreferenceSelector(TraitPrototype trait, SpriteSystem spriteSystem)
    {
        RobustXamlLoader.Load(this);

        Cost = trait.Cost;
        IconPlaceholder.Text = Loc.GetString("humanoid-profile-editor-trait-icon-placeholder");
        var costText = trait.Cost.ToString("+0;-0;0", CultureInfo.InvariantCulture);
        TitleLabel.Text = $"{Loc.GetString(trait.Name)} ({costText})";

        Checkbox.OnToggled += OnCheckBoxToggled;

        if (trait.Description is { } description)
        {
            var localizedDescription = Loc.GetString(description);
            DescriptionLabel.SetMessage(localizedDescription);
            Checkbox.ToolTip = localizedDescription;
        }
        else
        {
            DescriptionLabel.Visible = false;
        }

        if (trait.Icon is { } icon)
        {
            Icon.Texture = spriteSystem.Frame0(icon);
            Icon.Visible = true;
            IconPlaceholder.Visible = false;
        }
    }

    private void OnCheckBoxToggled(BaseButton.ButtonToggledEventArgs args)
    {
        PreferenceChanged?.Invoke(Preference);
    }
}
